"""Generate Solitude's voice lines with NoorVox (Tom's local TTS studio) and treat them for the game.

  python -I tools/voice/generate.py            # make whatever is missing
  python -I tools/voice/generate.py --force    # remake everything (raw takes too)
  python -I tools/voice/generate.py --fx-only  # re-run the radio treatment on existing raw takes

Raw takes go to tools/voice/raw/ (kept, so changing the filter never needs the GPU again).
Game files go to assets/audio/voice/<id>.wav, and assets/audio/voice/voice_lines.json lists them
(id, caption, file, seconds) for the game. Lines are read from solitude_voice_script.json.
"""
import json, os, re, subprocess, sys
import numpy as np
from scipy.io import wavfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import voice_fx  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
RAW = os.path.join(HERE, "raw")
OUT = os.path.join(ROOT, "assets", "audio", "voice")
NOORVOX = os.environ.get("NOORVOX", r"E:\Apps\NoorVox\noorvox.exe")

def nv(*args):
    r = subprocess.run([NOORVOX, *args, "--json", "--quiet"], capture_output=True, text=True, encoding="utf-8")
    try:
        env = json.loads(r.stdout)
    except json.JSONDecodeError:
        raise SystemExit(f"noorvox {args[0]}: no JSON (exit {r.returncode}): {r.stderr[-400:]}")
    if r.returncode != 0 or not env.get("success"):
        raise SystemExit(f"noorvox {' '.join(args[:2])} failed: {env.get('code')} {env.get('message')}")
    return env.get("data")

def caption(text):
    return re.sub(r"\s*\[[a-z ]+\]\s*", " ", text).strip()

def main():
    force = "--force" in sys.argv
    fx_only = "--fx-only" in sys.argv
    script = json.load(open(os.path.join(HERE, "solitude_voice_script.json"), encoding="utf-8"))
    d = script["defaults"]
    lines = script["lines"]
    os.makedirs(RAW, exist_ok=True); os.makedirs(OUT, exist_ok=True)

    # --- generate raw takes, one warm worker per model
    if not fx_only:
        todo = [l for l in lines if force or not os.path.exists(os.path.join(RAW, l["id"] + ".wav"))]
        for model in sorted({l.get("model", d["model"]) for l in todo}):
            batch = [l for l in todo if l.get("model", d["model"]) == model]
            worker = "solitude-" + model.split("-")[0]
            print(f"[voice] {model}: {len(batch)} lines (loading the model can take minutes)", flush=True)
            nv("workers", "start", "--worker", worker, "--model", model)
            try:
                for l in batch:
                    args = ["synth", "--worker", worker, "--model", model, "--voice", l["voice"], "--text", l["text"],
                            "--out", os.path.join(RAW, l["id"] + ".wav"), "--overwrite"]
                    if "seed" in l: args += ["--seed", str(l["seed"])]
                    if "speed" in l: args += ["--speed", str(l["speed"])]
                    r = nv(*args)
                    print(f"[voice]   {l['id']}: {r['durationMs'] / 1000:.1f} s", flush=True)
            finally:
                nv("workers", "stop", "--worker", worker)

    # --- treat for the game, write the manifest
    manifest = {"_about": "Generated by tools/voice/generate.py from solitude_voice_script.json. Do not edit by hand.",
                "wrecks": script["wrecks"], "lines": {}}
    for i, l in enumerate(lines):
        raw = os.path.join(RAW, l["id"] + ".wav")
        if not os.path.exists(raw):
            print(f"[voice] missing raw take: {l['id']}"); continue
        sr, x = voice_fx.load(raw)
        clip = l["id"].startswith(("digit_", "wrong_heading", "wrong_depth", "wrong_metres"))
        y = voice_fx.radio(x, sr, np.random.default_rng(1000 + i), clip=clip)
        dst = os.path.join(OUT, l["id"] + ".wav")
        voice_fx.save(dst, sr, y)
        manifest["lines"][l["id"]] = {"caption": caption(l["text"]), "file": f"res://assets/audio/voice/{l['id']}.wav",
                                      "seconds": round(len(y) / sr, 3)}
    with open(os.path.join(OUT, "voice_lines.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=1, ensure_ascii=False)
    print(f"[voice] {len(manifest['lines'])} lines ready in {OUT}")

if __name__ == "__main__":
    main()
