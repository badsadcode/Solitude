using System;
using System.Collections.Generic;
using Godot;
using Solitude.Core;
using Solitude.World;

namespace Solitude.Stations;

/// <summary>A deep-sea station somewhere on the seabed. Pure data, deterministic per world seed.</summary>
public sealed class StationSite
{
    public long Id;
    public string Layout;        // assets/stations/<Layout>.glb (generated by NoorLevel)
    public string Name;          // e.g. "RESEARCH STATION KESTREL-4"
    public Vector3 Position;     // on the seabed
    public float Yaw;
    public int Seed;             // per-visit content seed (loot, creatures, power)
    public bool Known;           // beacon heard or found on a map fragment
    /// <summary>The station family, from the layout name: research, outpost, habitat, works, deeplab, deck.</summary>
    public string Family => Layout.Contains('_') ? Layout.Substring(0, Layout.LastIndexOf('_')) : Layout;

    /// <summary>Where the submarine sits when docked (alongside the berth gantry).</summary>
    public Transform3D DockPose => new Transform3D(new Basis(Vector3.Up, Yaw), Position) * StationExterior.DockLocal;
}

/// <summary>
/// Where the stations are. The world is divided into 900 m cells; about half hold a station
/// on a reasonably flat patch. One "starter" station is always placed 300–400 m from spawn so
/// the first dive has somewhere to go.
/// </summary>
public sealed class StationDirectory
{
    public const float CellSize = 900f;

    /// <summary>Baked blockouts (tools/generate_stations.ps1 writes StationBank.g.cs).</summary>
    public static string[] Bank => StationBank.All;

    private static readonly string[] Prefix = { "RESEARCH STATION", "SURVEY OUTPOST", "MINING PLATFORM", "RELAY STATION", "HABITAT" };

    /// <summary>What a station of each family is called on the beacon.</summary>
    private static string FamilyPrefix(string layout) => layout.Substring(0, layout.LastIndexOf('_')) switch
    {
        "research" => "RESEARCH STATION",
        "outpost" => "SURVEY OUTPOST",
        "habitat" => "HABITAT",
        "works" => "MINING WORKS",
        "deeplab" => "DEEP LABORATORY",
        "deck" => "RELAY STATION",
        _ => "STATION",
    };
    private static readonly string[] Names =
    {
        "KESTREL", "MERIDIAN", "HOLLOW", "ANSELM", "TETHYS", "VIGIL", "CALDERA", "IRIS", "LANTERN",
        "OSPREY", "MOROSE", "THRESHOLD", "PALE", "CORMORANT", "ABYSSAL", "NADIR", "WREN", "SOUNDING",
    };

    private readonly TerrainGenerator _gen;
    private readonly Dictionary<long, StationSite> _cache = new();
    private readonly StationSite _starter;

    public StationDirectory(TerrainGenerator gen, Vector3 spawn)
    {
        _gen = gen;
        float a = Perlin.Hash(1, 2, gen.Seed) * Mathf.Tau;
        var p = spawn + new Vector3(MathF.Sin(a), 0, -MathF.Cos(a)) * (300f + Perlin.Hash(3, 4, gen.Seed) * 100f);
        _starter = MakeSite(-1, FindFlat(p.X, p.Z, 60f), 1000, gen.Seed);
        _starter.Known = true;
        _cache[_starter.Id] = _starter;
    }

    public StationSite Starter => _starter;

    private Vector3 FindFlat(float x, float z, float search)
    {
        Vector3 best = new(x, _gen.Height(x, z), z);
        float bestScore = -1f;
        for (int i = 0; i < 25; i++)
        {
            float px = x + ((i % 5) - 2) * search * 0.5f, pz = z + ((i / 5) - 2) * search * 0.5f;
            float score = _gen.Normal(px, pz, 15f).Y - MathF.Abs(_gen.Height(px, pz) + 480f) * 0.0005f;
            if (score > bestScore) { bestScore = score; best = new Vector3(px, _gen.Height(px, pz), pz); }
        }
        return best;
    }

    /// <summary>Dev: `-- --layout=outpost_01` makes every station use that blockout.</summary>
    public static string ForceLayout;

    private StationSite MakeSite(long id, Vector3 pos, int salt, int seed)
    {
        int h = (int)(Perlin.Hash((int)(id & 0xFFFF), (int)(id >> 16), seed + salt) * int.MaxValue);
        var rng = new Random(h);
        string layout = id == -1 ? StationBank.Starter[rng.Next(StationBank.Starter.Length)] : Bank[rng.Next(Bank.Length)]; // starter is a research station
        if (id != -1) rng.Next(Prefix.Length);   // (the old random prefix draw, kept so names stay put)
        return new StationSite
        {
            Id = id,
            Layout = layout,
            Name = $"{FamilyPrefix(layout)} {Names[rng.Next(Names.Length)]}-{rng.Next(1, 9)}",
            Position = pos,
            Yaw = (float)rng.NextDouble() * Mathf.Tau,
            Seed = rng.Next(),
        };
    }

    /// <summary>All stations within radius of p (cached, so Known flags persist).</summary>
    public IEnumerable<StationSite> Near(Vector3 p, float radius)
    {
        if (_starter.Position.DistanceTo(p) < radius) yield return _starter;
        int c0x = (int)MathF.Floor((p.X - radius) / CellSize), c1x = (int)MathF.Floor((p.X + radius) / CellSize);
        int c0z = (int)MathF.Floor((p.Z - radius) / CellSize), c1z = (int)MathF.Floor((p.Z + radius) / CellSize);
        for (int cz = c0z; cz <= c1z; cz++)
            for (int cx = c0x; cx <= c1x; cx++)
            {
                var s = Site(cx, cz);
                if (s != null && s.Position.DistanceTo(p) < radius) yield return s;
            }
    }

    /// <summary>Look a station up by id (for saves). Null if that cell holds none.</summary>
    public StationSite ById(long id) => id == -1 ? _starter : Site((int)(id >> 32), (int)(uint)id);

    /// <summary>All stations generated so far (the ones the save cares about).</summary>
    public IEnumerable<StationSite> Generated { get { foreach (var s in _cache.Values) if (s != null) yield return s; } }

    private StationSite Site(int cx, int cz)
    {
        long id = ((long)cx << 32) ^ (uint)cz;
        if (_cache.TryGetValue(id, out var cached)) return cached;
        StationSite site = null;
        if (Perlin.Hash(cx, cz, _gen.Seed + 501) < 0.5f)
        {
            float x = (cx + 0.15f + Perlin.Hash(cx, cz, _gen.Seed + 502) * 0.7f) * CellSize;
            float z = (cz + 0.15f + Perlin.Hash(cx, cz, _gen.Seed + 503) * 0.7f) * CellSize;
            var pos = FindFlat(x, z, 50f);
            // Keep clear of the starter.
            if (pos.DistanceTo(_starter.Position) > 400f) site = MakeSite(id, pos, 7, _gen.Seed);
        }
        _cache[id] = site;
        return site;
    }
}
