using System;
using System.Text;
using Godot;

namespace Solitude.UI;

/// <summary>
/// The credits: a slow scroll over the live title scene (the moored boat behind a dark veil), the studio
/// logo first. A second page holds the full licence texts: Godot's own (it asks for its notice to ship
/// with the game) and its third-party components, straight from the engine, plus the voice models'.
/// Keys: SPACE / DOWN / wheel faster, L licences, ESC / E / click back.
/// </summary>
public partial class CreditsScreen : Control
{
    public Action Closed;

    private static readonly Color Ink = new(0.78f, 0.9f, 0.82f), Dim = new(0.45f, 0.58f, 0.52f), Head = new(1f, 0.65f, 0.25f);
    private VBoxContainer _roll;
    private Control _clip;
    private RichTextLabel _licences;
    private float _y, _speed = 26f;
    private bool _onLicences;

    public override void _Ready()
    {
        // The HUD root has no size of its own, so fill the window explicitly (and follow it if it resizes).
        Position = Vector2.Zero;
        Size = GetViewportRect().Size;
        MouseFilter = MouseFilterEnum.Stop;
        AddChild(new ColorRect { Color = new Color(0f, 0.01f, 0.015f, 0.72f), MouseFilter = MouseFilterEnum.Ignore, AnchorRight = 1, AnchorBottom = 1 });

        _clip = new Control { ClipContents = true, MouseFilter = MouseFilterEnum.Ignore, AnchorRight = 1, AnchorBottom = 1 };
        AddChild(_clip);
        _roll = new VBoxContainer { MouseFilter = MouseFilterEnum.Ignore, Alignment = BoxContainer.AlignmentMode.Begin };
        _roll.AddThemeConstantOverride("separation", 6);
        _clip.AddChild(_roll);
        BuildRoll();

        _licences = new RichTextLabel
        {
            Visible = false, BbcodeEnabled = false, ScrollActive = true, SelectionEnabled = false, FitContent = false,
            AnchorLeft = 0.5f, AnchorRight = 0.5f, AnchorTop = 0f, AnchorBottom = 1f, OffsetLeft = -430, OffsetRight = 430, OffsetTop = 60, OffsetBottom = -60,
        };
        _licences.AddThemeColorOverride("default_color", Dim);
        _licences.AddThemeFontSizeOverride("normal_font_size", 13);
        _licences.Text = LicenceText();
        AddChild(_licences);

        var hint = new Label { Text = "SPACE faster   ·   L licences   ·   ESC back", HorizontalAlignment = HorizontalAlignment.Center };
        hint.AddThemeColorOverride("font_color", new Color(Dim, 0.7f));
        hint.AddThemeFontSizeOverride("font_size", 12);
        hint.SetAnchorsPreset(LayoutPreset.CenterBottom);
        hint.GrowHorizontal = GrowDirection.Both; hint.GrowVertical = GrowDirection.Begin;
        hint.Position += new Vector2(0, -18);
        AddChild(hint);

        _y = GetViewportRect().Size.Y * 0.92f;
        Layout();
    }

    private void Line(string text, int size, Color c, int gapBefore = 0)
    {
        if (gapBefore > 0) _roll.AddChild(new Control { CustomMinimumSize = new Vector2(0, gapBefore), MouseFilter = MouseFilterEnum.Ignore });
        var l = new Label { Text = text, HorizontalAlignment = HorizontalAlignment.Center, AutowrapMode = TextServer.AutowrapMode.WordSmart, MouseFilter = MouseFilterEnum.Ignore };
        l.CustomMinimumSize = new Vector2(760, 0);
        l.AddThemeColorOverride("font_color", c);
        l.AddThemeFontSizeOverride("font_size", size);
        _roll.AddChild(l);
    }

    private void Section(string title) => Line(title, 14, Head, 34);

    private void BuildRoll()
    {
        // The studio logo, small and pixelated (nearest-neighbour downscale), tinted phosphor like the splash.
        var tex = GD.Load<Texture2D>("res://assets/branding/biw_logo.png");
        if (tex != null)
        {
            var logo = new TextureRect
            {
                Texture = tex, CustomMinimumSize = new Vector2(240, 180), ExpandMode = TextureRect.ExpandModeEnum.IgnoreSize,
                StretchMode = TextureRect.StretchModeEnum.KeepAspectCentered, TextureFilter = TextureFilterEnum.Nearest,
                Modulate = new Color(0.6f, 1f, 0.85f), MouseFilter = MouseFilterEnum.Ignore, SizeFlagsHorizontal = SizeFlags.ShrinkCenter,
                // The logo is white on solid black: added, the black vanishes into the water behind it.
                Material = new CanvasItemMaterial { BlendMode = CanvasItemMaterial.BlendModeEnum.Add },
            };
            _roll.AddChild(logo);
        }
        Line("S O L I T U D E", 40, Ink, 18);
        Line("a Bad Ideas Works game", 15, Dim);

        Section("MADE BY");
        Line("Tom", 22, Ink);
        Line("design and creative direction · creatures · models and textures · title music · voices", 13, Dim);
        Line("Sage", 22, Ink, 12);
        Line("engineering · writing · sound · the Dive Log", 13, Dim);
        Line("(an AI: Claude, by Anthropic)", 12, new Color(Dim, 0.7f));

        Section("STATIONS");
        Line("generated by NoorLevel", 17, Ink);
        Line("Bad Ideas Works", 13, Dim);

        Section("VOICES");
        Line("made with NoorVox", 17, Ink);
        Line("Bad Ideas Works · every voice is designed from a description; none belongs to a real person", 13, Dim);
        Line("Martha · Steven · Mikey · Irena · Woytek · Ivan · Magda · Narrator 1 · Narrator 2 · Margaret", 14, Ink, 8);
        Line("designed by Tom", 13, Dim);
        Line("Hanna", 14, Ink, 8);
        Line("designed by Sage", 13, Dim);
        Line("voice models: Chatterbox (Resemble AI, MIT) · Qwen3-TTS (Qwen, Apache-2.0) · Kokoro-82M (hexgrad, Apache-2.0)", 12, Dim, 8);

        Section("ON THE RADIO");
        Line("the crews of the Haldane, the Meridian Bell, the Okonkwo, the Patience and the Grey Heron", 14, Ink);
        Line("who never got where they were going", 13, Dim);
        Line("Hanna Kowal, who did", 14, Ink, 8);

        Section("BUILT WITH");
        Line("Godot Engine", 17, Ink);
        Line("godotengine.org · MIT licence · full notices on the licences page (L)", 13, Dim);
        Line("C# and .NET · MIT licence", 13, Dim, 4);

        Section("THANK YOU");
        Line("for going down.", 17, Ink);

        Line("Five hundred metres down, somebody answered.", 15, new Color(0.55f, 1f, 0.7f), 90);
        _roll.AddChild(new Control { CustomMinimumSize = new Vector2(0, 260), MouseFilter = MouseFilterEnum.Ignore });
    }

    /// <summary>Godot's licence and every third-party component it ships, straight from the engine; then the voice models.</summary>
    private static string LicenceText()
    {
        var sb = new StringBuilder();
        sb.AppendLine("LICENCES\n");
        sb.AppendLine("This game uses Godot Engine, available under the following licence:\n");
        sb.AppendLine(Engine.GetLicenseText());
        sb.AppendLine("\n— Godot Engine's third-party components —\n");
        foreach (var info in Engine.GetCopyrightInfo())
        {
            var d = info;
            sb.AppendLine(d["name"].AsString());
            foreach (var part in d["parts"].AsGodotArray())
            {
                var p = part.AsGodotDictionary();
                foreach (var c in p["copyright"].AsStringArray()) sb.AppendLine("  © " + c);
                sb.AppendLine("  Licence: " + p["license"].AsString());
            }
        }
        sb.AppendLine("\n— Licence texts —\n");
        var licences = Engine.GetLicenseInfo();
        foreach (var key in licences.Keys)
        {
            sb.AppendLine("[" + key.AsString() + "]");
            sb.AppendLine(licences[key].AsString());
            sb.AppendLine();
        }
        sb.AppendLine("\n— Voices —\n");
        sb.AppendLine("The voice lines were generated locally with NoorVox (Bad Ideas Works) using these models:");
        sb.AppendLine("  Chatterbox, © Resemble AI, MIT licence. Its audio carries Resemble AI's inaudible Perth watermark.");
        sb.AppendLine("  Qwen3-TTS, © Alibaba Cloud (Qwen team), Apache License 2.0.");
        sb.AppendLine("  Kokoro-82M, © hexgrad, Apache License 2.0.");
        sb.AppendLine("No model files are distributed with this game; only the audio they produced.");
        return sb.ToString();
    }

    private void Layout()
    {
        float w = GetViewportRect().Size.X;
        _roll.Size = new Vector2(760, _roll.GetCombinedMinimumSize().Y);
        _roll.Position = new Vector2((w - 760f) / 2f, _y);
    }

    public override void _Process(double delta)
    {
        if (Size != GetViewportRect().Size) Size = GetViewportRect().Size;
        if (_onLicences) return;
        float fast = Input.IsKeyPressed(Key.Space) || Input.IsKeyPressed(Key.Down) ? 6f : 1f;
        _y -= _speed * fast * (float)delta;
        Layout();
        // When the last line has gone by, start again from the bottom.
        if (_y < -_roll.Size.Y + 120f) _y = GetViewportRect().Size.Y;
    }

    public override void _Input(InputEvent e)
    {
        if (e is InputEventKey k && k.Pressed && !k.Echo)
        {
            if (k.Keycode is Key.Escape or Key.E or Key.Tab) { Close(); AcceptEvent(); }
            else if (k.Keycode == Key.L) { _onLicences = !_onLicences; _licences.Visible = _onLicences; _clip.Visible = !_onLicences; AcceptEvent(); }
        }
        else if (e is InputEventMouseButton mb && mb.Pressed)
        {
            if (mb.ButtonIndex == MouseButton.WheelDown && !_onLicences) { _y -= 60f; AcceptEvent(); }
            else if (mb.ButtonIndex == MouseButton.WheelUp && !_onLicences) { _y += 60f; AcceptEvent(); }
            else if (mb.ButtonIndex == MouseButton.Left && !_onLicences) { Close(); AcceptEvent(); }
        }
    }

    private void Close()
    {
        Closed?.Invoke();
        QueueFree();
    }
}
